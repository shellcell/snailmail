func validateManifestFile(file buildgraph.ManifestFile, index int, files []buildgraph.ManifestFile) error {
	if file.Path == "" || path.IsAbs(file.Path) || path.Clean(file.Path) != file.Path || file.Path == "." || strings.HasPrefix(file.Path, "../") || strings.ContainsRune(file.Path, '\\') {
		return fmt.Errorf("repository manifest contains unsafe path %q", file.Path)
	}
	if file.Path == buildgraph.ManifestFilename {
		return fmt.Errorf("repository manifest includes itself")
	}
	if index > 0 && files[index-1].Path >= file.Path {
		return errors.New("repository manifest file list is not uniquely sorted")
	}
	if file.Size < 0 {
		return fmt.Errorf("repository file %q has a negative size", file.Path)
	}
	decoded, err := hex.DecodeString(file.SHA256)
	if err != nil || len(decoded) != sha256.Size {
		return fmt.Errorf("repository file %q has an invalid SHA-256", file.Path)
	}
	return nil
}

func hashRepositoryFile(root, name string) (int64, string, error) {
	filename := filepath.Join(root, filepath.FromSlash(name))
	info, err := os.Lstat(filename)
	if err != nil {
		return 0, "", fmt.Errorf("inspect repository file %q: %w", name, err)
	}
	if !info.Mode().IsRegular() {
		return 0, "", fmt.Errorf("repository file %q is not a regular file", name)
	}
	file, err := os.Open(filename)
	if err != nil {
		return 0, "", fmt.Errorf("open repository file %q: %w", name, err)
	}
	hash := sha256.New()
	size, readErr := io.Copy(hash, file)
	closeErr := file.Close()
	if readErr != nil {
		return 0, "", fmt.Errorf("hash repository file %q: %w", name, readErr)
	}
	if closeErr != nil {
		return 0, "", fmt.Errorf("close repository file %q: %w", name, closeErr)
	}
	return size, hex.EncodeToString(hash.Sum(nil)), nil
}

func rejectUnexpectedFiles(root string, expected map[string]bool) error {
	var actual []string
	err := filepath.WalkDir(root, func(name string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.Type()&fs.ModeSymlink != 0 {
			return fmt.Errorf("repository contains symbolic link %q", name)
		}
		if entry.IsDir() {
			return nil
		}
		if !entry.Type().IsRegular() {
			return fmt.Errorf("repository contains non-regular file %q", name)
		}
		relative, err := filepath.Rel(root, name)
		if err != nil {
			return err
		}
		actual = append(actual, filepath.ToSlash(relative))
		return nil
	})
	if err != nil {
		return err
	}
	sort.Strings(actual)
	for _, name := range actual {
		if !expected[name] {
			return fmt.Errorf("repository contains unexpected file %q", name)
		}
		delete(expected, name)
	}
	if len(expected) != 0 {
		return errors.New("repository is missing files declared by its manifest")
	}
	return nil
}

func requireJSONEOF(decoder *json.Decoder) error {
	var extra any
	if err := decoder.Decode(&extra); !errors.Is(err, io.EOF) {
		if err == nil {
			return errors.New("repository manifest contains more than one JSON value")
		}
		return fmt.Errorf("decode repository manifest: %w", err)
	}
	return nil
}

func verifyPyPIStructure(root string, manifest buildgraph.RepositoryManifest) ([]domain.Blob, error) {
	var blobs []domain.Blob
	for _, file := range manifest.Files {
		if strings.HasPrefix(file.Path, "simple/") {
			if path.Base(file.Path) != "index.html" {
				return nil, fmt.Errorf("unexpected PyPI index path %q", file.Path)
			}
			continue
		}
		parts := strings.Split(file.Path, "/")
		if len(parts) != 3 || parts[0] != "packages" || parts[1] != file.SHA256 || !pypi.IsDistributionFilename(parts[2]) {
			return nil, fmt.Errorf("unexpected PyPI repository path %q", file.Path)
		}
		name := filepath.Join(root, filepath.FromSlash(file.Path))
		packageFile, err := os.Open(name)
		if err != nil {
			return nil, fmt.Errorf("open PyPI package %q: %w", file.Path, err)
		}
		facts, inspectErr := pypi.Inspect(parts[2], packageFile, file.Size)
		closeErr := packageFile.Close()
		if inspectErr != nil {
			return nil, inspectErr
		}
		if closeErr != nil {
			return nil, fmt.Errorf("close PyPI package %q: %w", file.Path, closeErr)
		}
		blobs = append(blobs, domain.Blob{Filename: parts[2], Size: file.Size, SHA256: file.SHA256, Facts: facts})
	}
	expectedArtifact, err := pypi.Build(blobs)
	if err != nil {
		return nil, fmt.Errorf("rebuild PyPI structure: %w", err)
	}
	generatedAt, err := time.Parse(time.RFC3339, manifest.GeneratedAt)
	if err != nil {
		return nil, err
	}
	_, expectedManifest, err := buildgraph.Finalize(expectedArtifact, generatedAt)
	if err != nil {
		return nil, fmt.Errorf("finalize expected PyPI structure: %w", err)
	}
	if !reflect.DeepEqual(expectedManifest, manifest) {
		return nil, errors.New("PyPI indexes or verification metadata do not match package bytes")
	}
	return blobs, nil
}

func verifyDebStructure(root string, manifest buildgraph.RepositoryManifest) ([]domain.Blob, error) {
	var blobs []domain.Blob
	for _, file := range manifest.Files {
		if strings.HasPrefix(file.Path, "dists/") {
			continue
		}
		if !strings.HasPrefix(file.Path, "pool/") || !deb.IsPackageFilename(path.Base(file.Path)) {
			return nil, fmt.Errorf("unexpected Debian repository path %q", file.Path)
		}
		name := filepath.Join(root, filepath.FromSlash(file.Path))
		packageFile, err := os.Open(name)
		if err != nil {
			return nil, fmt.Errorf("open Debian package %q: %w", file.Path, err)
		}
		facts, inspectErr := deb.Inspect(path.Base(file.Path), packageFile, file.Size)
		closeErr := packageFile.Close()
		if inspectErr != nil {
			return nil, inspectErr
		}
		if closeErr != nil {
			return nil, fmt.Errorf("close Debian package %q: %w", file.Path, closeErr)
		}
		md5Value, sha1Value, err := legacyChecksums(name)
		if err != nil {
			return nil, err
		}
		blobs = append(blobs, domain.Blob{
			Filename: path.Base(file.Path),
			Size:     file.Size,
			MD5:      md5Value,
			SHA1:     sha1Value,
			SHA256:   file.SHA256,
			Facts:    facts,
		})
	}
	generatedAt, err := time.Parse(time.RFC3339, manifest.GeneratedAt)
	if err != nil {
		return nil, err
	}
	expectedArtifact, err := deb.Build(blobs, deb.BuildOptions{
		Suite:         manifest.Install.Suite,
		Component:     manifest.Install.Component,
		Architectures: manifest.Install.Architectures,
		GeneratedAt:   generatedAt,
	})
	if err != nil {
		return nil, fmt.Errorf("rebuild Debian structure: %w", err)
	}
	_, expectedManifest, err := buildgraph.Finalize(expectedArtifact, generatedAt)
	if err != nil {
		return nil, fmt.Errorf("finalize expected Debian structure: %w", err)
	}
	if !reflect.DeepEqual(expectedManifest, manifest) {
		return nil, errors.New("Debian indexes or verification metadata do not match package bytes")
	}
	return blobs, nil
}

