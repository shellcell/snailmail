func legacyChecksums(name string) (string, string, error) {
	file, err := os.Open(name)
	if err != nil {
		return "", "", err
	}
	md5Hash := md5.New()
	sha1Hash := sha1.New()
	_, readErr := io.Copy(io.MultiWriter(md5Hash, sha1Hash), file)
	closeErr := file.Close()
	if readErr != nil {
		return "", "", readErr
	}
	if closeErr != nil {
		return "", "", closeErr
	}
	return hex.EncodeToString(md5Hash.Sum(nil)), hex.EncodeToString(sha1Hash.Sum(nil)), nil
}

func snapshotRepository(ctx context.Context, source string, manifest buildgraph.RepositoryManifest) (string, error) {
	snapshot, err := os.MkdirTemp("", ".snailmail-repository-*")
	if err != nil {
		return "", fmt.Errorf("create repository snapshot: %w", err)
	}
	if err := os.Chmod(snapshot, 0o755); err != nil {
		_ = os.RemoveAll(snapshot)
		return "", fmt.Errorf("make repository snapshot readable: %w", err)
	}
	keep := false
	defer func() {
		if !keep {
			_ = os.RemoveAll(snapshot)
		}
	}()
	files := make([]buildgraph.ManifestFile, 0, len(manifest.Files)+1)
	files = append(files, manifest.Files...)
	manifestInfo, err := os.Lstat(filepath.Join(source, buildgraph.ManifestFilename))
	if err != nil {
		return "", err
	}
	if !manifestInfo.Mode().IsRegular() || manifestInfo.Size() > maxManifestSize {
		return "", errors.New("repository manifest is not a bounded regular file")
	}
	files = append(files, buildgraph.ManifestFile{Path: buildgraph.ManifestFilename, Size: manifestInfo.Size()})
	for _, file := range files {
		if err := ctx.Err(); err != nil {
			return "", err
		}
		name := filepath.Join(source, filepath.FromSlash(file.Path))
		info, err := os.Lstat(name)
		if err != nil {
			return "", err
		}
		if !info.Mode().IsRegular() || info.Size() != file.Size {
			return "", fmt.Errorf("repository file %q changed before snapshot", file.Path)
		}
		target := filepath.Join(snapshot, filepath.FromSlash(file.Path))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return "", err
		}
		if err := copyFile(name, target, file.Size); err != nil {
			return "", err
		}
	}
	keep = true
	return snapshot, nil
}

func copyFile(sourceName, targetName string, expectedSize int64) error {
	source, err := os.Open(sourceName)
	if err != nil {
		return err
	}
	destination, err := os.OpenFile(targetName, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		_ = source.Close()
		return err
	}
	written, copyErr := io.Copy(destination, io.LimitReader(source, expectedSize+1))
	closeDestinationErr := destination.Close()
	closeSourceErr := source.Close()
	if copyErr != nil {
		return copyErr
	}
	if written != expectedSize {
		return fmt.Errorf("repository file %q changed while snapshotting", sourceName)
	}
	if closeDestinationErr != nil {
		return closeDestinationErr
	}
	return closeSourceErr
}
