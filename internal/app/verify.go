const (
	maxManifestSize    = 8 << 20
	maxRepositoryFiles = 20_000
	maxRepositoryBytes = 4 << 30
)

// VerifyRepository checks the management manifest and every generated byte.
func VerifyRepository(root string) (buildgraph.RepositoryManifest, error) {
	manifest, _, err := verifyRepository(root)
	return manifest, err
}

func verifyRepository(root string) (buildgraph.RepositoryManifest, []domain.Blob, error) {
	absolute, err := filepath.Abs(root)
	if err != nil {
		return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("resolve repository: %w", err)
	}
	absolute, err = filepath.EvalSymlinks(absolute)
	if err != nil {
		return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("resolve repository release: %w", err)
	}
	manifestPath := filepath.Join(absolute, buildgraph.ManifestFilename)
	manifestFile, err := os.Open(manifestPath)
	if err != nil {
		return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("open repository manifest: %w", err)
	}
	manifestBytes, readErr := io.ReadAll(io.LimitReader(manifestFile, maxManifestSize+1))
	closeErr := manifestFile.Close()
	if readErr != nil {
		return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("read repository manifest: %w", readErr)
	}
	if closeErr != nil {
		return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("close repository manifest: %w", closeErr)
	}
	if len(manifestBytes) > maxManifestSize {
		return buildgraph.RepositoryManifest{}, nil, errors.New("repository manifest exceeds 8 MiB")
	}
	decoder := json.NewDecoder(strings.NewReader(string(manifestBytes)))
	decoder.DisallowUnknownFields()
	var manifest buildgraph.RepositoryManifest
	if err := decoder.Decode(&manifest); err != nil {
		return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("decode repository manifest: %w", err)
	}
	if err := requireJSONEOF(decoder); err != nil {
		return buildgraph.RepositoryManifest{}, nil, err
	}
	if manifest.SchemaVersion != buildgraph.ManifestSchema {
		return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("unsupported repository schema %d", manifest.SchemaVersion)
	}
	if manifest.Format == "" {
		return buildgraph.RepositoryManifest{}, nil, errors.New("repository manifest has no format")
	}
	if _, err := time.Parse(time.RFC3339, manifest.GeneratedAt); err != nil {
		return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("invalid generation time: %w", err)
	}
	if len(manifest.Files) > maxRepositoryFiles {
		return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("repository has more than %d files", maxRepositoryFiles)
	}
	var repositorySize int64
	for _, file := range manifest.Files {
		if file.Size < 0 || file.Size > maxRepositoryBytes-repositorySize {
			return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("repository exceeds the %d byte verification limit", maxRepositoryBytes)
		}
		repositorySize += file.Size
	}

	expected := map[string]bool{buildgraph.ManifestFilename: true}
	for index, file := range manifest.Files {
		if err := validateManifestFile(file, index, manifest.Files); err != nil {
			return buildgraph.RepositoryManifest{}, nil, err
		}
		expected[file.Path] = true
		actualSize, actualHash, err := hashRepositoryFile(absolute, file.Path)
		if err != nil {
			return buildgraph.RepositoryManifest{}, nil, err
		}
		if actualSize != file.Size || actualHash != file.SHA256 {
			return buildgraph.RepositoryManifest{}, nil, fmt.Errorf("repository file %q does not match its manifest", file.Path)
		}
	}
	if buildgraph.TreeDigest(manifest.Files) != manifest.TreeSHA256 {
		return buildgraph.RepositoryManifest{}, nil, errors.New("repository tree digest does not match its manifest")
	}
	if err := rejectUnexpectedFiles(absolute, expected); err != nil {
		return buildgraph.RepositoryManifest{}, nil, err
	}
	var blobs []domain.Blob
	if manifest.Format == pypi.FormatID {
		blobs, err = verifyPyPIStructure(absolute, manifest)
		if err != nil {
			return buildgraph.RepositoryManifest{}, nil, err
		}
	}
	if manifest.Format == deb.FormatID {
		blobs, err = verifyDebStructure(absolute, manifest)
		if err != nil {
			return buildgraph.RepositoryManifest{}, nil, err
		}
	}
	if manifest.Format == helm.FormatID {
		blobs, err = verifyHelmStructure(absolute, manifest)
		if err != nil {
			return buildgraph.RepositoryManifest{}, nil, err
		}
	}
	return manifest, blobs, nil
}

// VerifyPyPIClient installs every unique project version with pip from an
// ephemeral HTTP server over the verified tree.
func VerifyPyPIClient(ctx context.Context, root, python string) (buildgraph.RepositoryManifest, int, error) {
	release, err := filepath.Abs(root)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("resolve repository: %w", err)
	}
	release, err = filepath.EvalSymlinks(release)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("resolve repository release: %w", err)
	}
	manifest, _, err := verifyRepository(release)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, err
	}
	snapshot, err := snapshotRepository(ctx, release, manifest)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, err
	}
	defer os.RemoveAll(snapshot)
	manifest, blobs, err := verifyRepository(snapshot)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, err
	}
	if manifest.Format != pypi.FormatID {
		return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("repository format is %q, not %q", manifest.Format, pypi.FormatID)
	}
	if python == "" {
		python = "python3"
	}
	python, err = exec.LookPath(python)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("find Python client: %w", err)
	}
	wheels := make(map[string]bool)
	for _, blob := range blobs {
		if strings.HasSuffix(strings.ToLower(blob.Filename), ".whl") {
			wheels[pypi.NormalizeName(blob.Facts.Name)+"\x00"+blob.Facts.Version] = true
		}
		for _, requirement := range blob.Facts.Requirements {
			if strings.Contains(requirement, "@") {
				return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("host verification rejects direct URL requirement %q; use an isolated runner", requirement)
			}
		}
	}
	for _, verification := range manifest.VerificationCases {
		if !wheels[verification.Project+"\x00"+verification.Version] {
			return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("%s==%s has no wheel; source distribution verification requires an isolated runner", verification.Project, verification.Version)
		}
	}

	server := httptest.NewServer(http.FileServer(http.Dir(snapshot)))
	defer server.Close()

	for _, verification := range manifest.VerificationCases {
		sandbox, err := os.MkdirTemp("", ".snailmail-pip-*")
		if err != nil {
			return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("create pip sandbox: %w", err)
		}
		target := filepath.Join(sandbox, "target")
		home := filepath.Join(sandbox, "home")
		temporary := filepath.Join(sandbox, "tmp")
		if err := os.MkdirAll(home, 0o700); err != nil {
			_ = os.RemoveAll(sandbox)
			return buildgraph.RepositoryManifest{}, 0, err
		}
		if err := os.MkdirAll(temporary, 0o700); err != nil {
			_ = os.RemoveAll(sandbox)
			return buildgraph.RepositoryManifest{}, 0, err
		}
		arguments := []string{
			"-I", "-m", "pip", "install",
			"--disable-pip-version-check",
			"--no-input",
			"--no-build-isolation",
			"--only-binary=:all:",
			"--no-compile",
			"--index-url", server.URL + "/" + manifest.Install.IndexPath,
			"--target", target,
			"--", verification.Project + "==" + verification.Version,
		}
		command := exec.CommandContext(ctx, python, arguments...)
		command.Dir = sandbox
		command.Env = []string{
			"HOME=" + home,
			"TMPDIR=" + temporary,
			"PATH=" + os.Getenv("PATH"),
			"LANG=C.UTF-8",
			"PIP_CONFIG_FILE=" + os.DevNull,
			"PIP_NO_CACHE_DIR=1",
			"PYTHONNOUSERSITE=1",
			"HTTP_PROXY=http://127.0.0.1:9",
			"HTTPS_PROXY=http://127.0.0.1:9",
			"http_proxy=http://127.0.0.1:9",
			"https_proxy=http://127.0.0.1:9",
			"NO_PROXY=127.0.0.1,localhost",
			"no_proxy=127.0.0.1,localhost",
		}
		output, commandErr := command.CombinedOutput()
		removeErr := os.RemoveAll(sandbox)
		if commandErr != nil {
			return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("pip install %s==%s: %w\n%s", verification.Project, verification.Version, commandErr, strings.TrimSpace(string(output)))
		}
		if removeErr != nil {
			return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("remove pip target: %w", removeErr)
		}
	}
	return manifest, len(manifest.VerificationCases), nil
}

// VerifyDebClient resolves and extracts each planned package version in its own
// bounded, network-isolated Debian container.
func VerifyDebClient(ctx context.Context, root, runner, image string, maxWorkspaceBytes int64) (buildgraph.RepositoryManifest, int, error) {
	release, err := filepath.Abs(root)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("resolve repository: %w", err)
	}
	release, err = filepath.EvalSymlinks(release)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("resolve repository release: %w", err)
	}
	manifest, _, err := verifyRepository(release)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, err
	}
	snapshot, err := snapshotRepository(ctx, release, manifest)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, err
	}
	defer os.RemoveAll(snapshot)
	manifest, blobs, err := verifyRepository(snapshot)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, err
	}
	if manifest.Format != deb.FormatID {
		return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("repository format is %q, not %q", manifest.Format, deb.FormatID)
	}
	if runner == "" {
		runner = "podman"
	}
	runner, err = exec.LookPath(runner)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, fmt.Errorf("find container runner: %w", err)
	}
	if !digestPinnedImage(image) {
		return buildgraph.RepositoryManifest{}, 0, errors.New("a digest-pinned Debian verification image is required")
	}
	workspaceBytes, err := debWorkspaceSize(blobs, maxWorkspaceBytes)
	if err != nil {
		return buildgraph.RepositoryManifest{}, 0, err
	}
	for _, verification := range manifest.VerificationCases {
		if err := verifyDebCase(ctx, runner, image, snapshot, workspaceBytes, manifest, verification); err != nil {
			return buildgraph.RepositoryManifest{}, 0, err
		}
	}
	return manifest, len(manifest.VerificationCases), nil
}

func verifyDebCase(ctx context.Context, runner, image, snapshot string, workspaceBytes int64, manifest buildgraph.RepositoryManifest, verification domain.VerificationCase) error {
	platform, err := debOCIPlatform(verification.Architecture)
	if err != nil {
		return err
	}
	caseCtx, cancel := context.WithTimeout(ctx, 2*time.Minute)
	defer cancel()
	memoryBytes := workspaceBytes + 512<<20
	arguments := []string{
		"run", "--rm", "--pull=missing", "--network=none",
		"--platform", platform,
		"--read-only", "--memory=" + strconv.FormatInt(memoryBytes, 10), "--cpus=2", "--pids-limit=256",
		"--ulimit", "fsize=536870912:536870912", "--ulimit", "nofile=1024:1024",
		"--security-opt", "no-new-privileges",
		"--volume", snapshot + ":/target/repo:ro,Z",
		"--env", "DEBIAN_FRONTEND=noninteractive",
		"--env", "SNAILMAIL_SUITE=" + manifest.Install.Suite,
		"--env", "SNAILMAIL_COMPONENT=" + manifest.Install.Component,
		"--env", "SNAILMAIL_ARCHITECTURE=" + verification.Architecture,
		"--env", "SNAILMAIL_PACKAGE=" + verification.Package,
		"--env", "SNAILMAIL_VERSION=" + verification.Version,
		"--tmpfs", "/tmp:rw,size=64m,mode=1777",
		"--tmpfs", "/target:rw,size=" + strconv.FormatInt(workspaceBytes, 10) + ",mode=0755",
		image,
		"sh", "-euc", `
for directory in bin etc lib lib64 sbin usr var; do
    test -e "/$directory" && cp -a "/$directory" /target/
done
mkdir -p /target/dev /target/proc /target/sys /target/tmp
chmod 1777 /target/tmp
: >/target/dev/null
rm -rf /target/etc/apt/sources.list.d/* /target/etc/apt/sources.list
mkdir -p /target/var/lib/apt/lists/partial /target/var/cache/apt/archives/partial
printf 'deb [trusted=yes arch=%s] file:/repo %s %s\n' "$SNAILMAIL_ARCHITECTURE" "$SNAILMAIL_SUITE" "$SNAILMAIL_COMPONENT" >/target/etc/apt/sources.list
chroot /target apt-get -o APT::Sandbox::User=root -o Acquire::Languages=none update
chroot /target apt-get -o APT::Sandbox::User=root install -y --reinstall --no-install-recommends "$SNAILMAIL_PACKAGE=$SNAILMAIL_VERSION"
status=$(chroot /target dpkg-query -W -f='${Status} ${Version}' "$SNAILMAIL_PACKAGE")
test "$status" = "install ok installed $SNAILMAIL_VERSION"
`,
	}
	command := exec.CommandContext(caseCtx, runner, arguments...)
	command.Env = os.Environ()
	output, err := command.CombinedOutput()
	if err != nil {
		return fmt.Errorf("Debian client verification for %s=%s/%s: %w\n%s", verification.Package, verification.Version, verification.Architecture, err, strings.TrimSpace(string(output)))
	}
	return nil
}

func debWorkspaceSize(blobs []domain.Blob, maximum int64) (int64, error) {
	const (
		baseRootBytes = 256 << 20
		minimumBytes  = 768 << 20
	)
	if maximum <= 0 {
		return 0, errors.New("Debian verification workspace limit must be positive")
	}
	required := int64(baseRootBytes)
	for _, blob := range blobs {
		addition := blob.Size + blob.Facts.InstalledSize
		if addition < 0 || required > maximum-addition {
			return 0, fmt.Errorf("Debian verification requires more than the configured %d byte workspace", maximum)
		}
		required += addition
	}
	if required < minimumBytes {
		required = minimumBytes
	}
	if required > maximum {
		return 0, fmt.Errorf("Debian verification requires %d bytes, above the configured %d byte workspace", required, maximum)
	}
	return required, nil
}

func digestPinnedImage(image string) bool {
	digest := ""
	if separator := strings.LastIndex(image, "@sha256:"); separator >= 0 {
		digest = image[separator+len("@sha256:"):]
	} else if strings.HasPrefix(image, "sha256:") {
		digest = strings.TrimPrefix(image, "sha256:")
	}
	if len(digest) != sha256.Size*2 || digest != strings.ToLower(digest) {
		return false
	}
	decoded, err := hex.DecodeString(digest)
	return err == nil && len(decoded) == sha256.Size
}

func debOCIPlatform(architecture string) (string, error) {
	platforms := map[string]string{
		"amd64":    "linux/amd64",
		"arm64":    "linux/arm64",
		"armhf":    "linux/arm/v7",
		"armel":    "linux/arm/v5",
		"i386":     "linux/386",
		"mips64el": "linux/mips64le",
		"ppc64el":  "linux/ppc64le",
		"s390x":    "linux/s390x",
	}
	platform := platforms[architecture]
	if platform == "" {
		return "", fmt.Errorf("no OCI platform mapping for Debian architecture %q", architecture)
	}
	return platform, nil
}

